type SupportedLocale = keyof typeof partialFallbackResources;
type FallbackCatalog = Record<string, string>;

function completeFallbackResources() {
  const locales = Object.keys(partialFallbackResources) as SupportedLocale[];
  const partialCatalogs = Object.fromEntries(
    locales.map((locale) => [locale, partialFallbackResources[locale].fallback]),
  ) as unknown as Record<SupportedLocale, FallbackCatalog>;
  const keys = new Set(locales.flatMap((locale) => Object.keys(partialCatalogs[locale])));

  const fallbackOrder: Record<SupportedLocale, SupportedLocale[]> = {
    fr: ['fr', 'en', 'ar'],
    en: ['en', 'fr', 'ar'],
    ar: ['ar', 'fr', 'en'],
  };

  return Object.fromEntries(
    locales.map((locale) => [
      locale,
      {
        fallback: Object.fromEntries(
          [...keys].map((key) => {
            const sourceLocale = fallbackOrder[locale].find(
              (candidate) => partialCatalogs[candidate][key] !== undefined,
            );
            return [key, partialCatalogs[sourceLocale ?? 'fr'][key]];
          }),
        ),
      },
    ]),
  ) as Record<SupportedLocale, { fallback: FallbackCatalog }>;
}

